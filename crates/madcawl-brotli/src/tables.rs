/// The insert and copy length codes of an insert-and-copy symbol
pub(crate) fn split_command(cmd: usize) -> (usize, usize) {
    // the insert and copy code ranges of each 64-symbol cell
    #[rustfmt::skip]
    const CELLS: [(u8, u8); 11] =
        [(0, 0), (0, 8), (0, 0), (0, 8), (8, 0), (8, 8), (0, 16), (16, 0), (8, 16), (16, 8), (16, 16)];
    let (i, c) = CELLS[cmd >> 6];
    (i as usize + ((cmd >> 3) & 7), c as usize + (cmd & 7))
}

/// The context id of the next literal for a context mode and the last
/// two bytes
#[inline]
pub(crate) fn literal_context(mode: u8, p1: u8, p2: u8) -> usize {
    match mode {
        0 => (p1 & 0x3f) as usize,
        1 => (p1 >> 2) as usize,
        2 => (LUT0[p1 as usize] | LUT1[p2 as usize]) as usize,
        _ => ((LUT2[p1 as usize] << 3) | LUT2[p2 as usize]) as usize,
    }
}

