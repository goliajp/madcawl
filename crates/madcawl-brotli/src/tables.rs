#[cfg(test)]
pub(crate) fn crc32(v: &[u8]) -> u32 {
    let mut crc = 0xffff_ffffu32;
    for &b in v {
        let mut c = (crc ^ u32::from(b)) & 0xff;
        for _ in 0..8 {
            c = if c & 1 == 1 { 0xedb8_8320 ^ (c >> 1) } else { c >> 1 };
        }
        crc = c ^ (crc >> 8);
    }
    crc ^ 0xffff_ffff
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_lookup_tables_have_the_published_check_values() {
        assert_eq!(crc32(&LUT0), 0x8e91_efb7);
        assert_eq!(crc32(&LUT1), 0xd01a_32f4);
        assert_eq!(crc32(&LUT2), 0x0dd7_a0d6);
    }

    #[test]
    fn each_length_code_range_ends_where_the_next_begins() {
        for t in [&INSERT[..], &COPY[..], &BLOCK_COUNT[..]] {
            for w in t.windows(2) {
                assert_eq!(w[0].0 + (1 << w[0].1), w[1].0);
            }
        }
        assert_eq!(split_command(0), (0, 0));
        assert_eq!(split_command(703), (23, 23));
        assert_eq!(split_command(384 + 9), (1, 17));
    }
}
